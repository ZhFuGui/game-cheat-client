"""Generate diagnostic field names from the two already frozen descriptors (stdlib only)."""
import argparse
import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DESCRIPTORS = ["protocol/sources/cs2_reader/reader-v2.descriptor.pb",
               "protocol/sources/pubg_reader/protocol-descriptor.pb"]
TARGET = ROOT / "src/adapters/sources/inspection/generated_schema.hpp"


def varint(data, pos):
    value = 0
    for shift in range(0, 70, 7):
        byte = data[pos]
        pos += 1
        value |= (byte & 127) << shift
        if byte < 128:
            return value, pos
    raise ValueError("Invalid descriptor varint")


def fields(data):
    result, pos = {}, 0
    while pos < len(data):
        tag, pos = varint(data, pos)
        number, wire = tag >> 3, tag & 7
        if wire == 0:
            value, pos = varint(data, pos)
        elif wire == 2:
            size, pos = varint(data, pos)
            value, pos = data[pos:pos + size], pos + size
        else:
            raise ValueError("Unexpected descriptor field")
        result.setdefault(number, []).append(value)
    return result


def text(value, number, default=b""):
    return value.get(number, [default])[0].decode("utf-8")


def generate():
    messages, hashes = {}, []

    def message(data, prefix):
        value = fields(data)
        name = prefix + "." + text(value, 1)
        members = []
        for raw in value.get(2, []):
            field = fields(raw)
            members.append((field[3][0], text(field, 1), field[5][0],
                            text(field, 6).lstrip("."), field[4][0] == 3))
        messages[name] = members
        for nested in value.get(3, []):
            message(nested, name)

    for path in DESCRIPTORS:
        data = (ROOT / path).read_bytes()
        hashes.append(f"// {path}: {hashlib.sha256(data).hexdigest()}")
        for raw in fields(data)[1]:
            file = fields(raw)
            for raw_message in file.get(4, []):
                message(raw_message, text(file, 2))
    q = lambda s: json.dumps(s, ensure_ascii=True)
    lines = ["#pragma once", "// Generated by tools/generate-source-inspection-schema.py; do not edit.",
             *hashes, '#include "protobuf_json.hpp"',
             "namespace mousebox::sources::inspection::generated", "{",
             "inline constexpr Field fields[]{"]
    spans, offset = [], 0
    for name, members in sorted(messages.items()):
        spans.append((name, offset, len(members)))
        for number, field_name, kind, child, repeated in members:
            lines.append(f"    {{{number}, {q(field_name)}, {kind}, {q(child)}, {str(repeated).lower()}}},")
        offset += len(members)
    lines += ["};", "inline constexpr Message messages[]{"]
    lines += [f"    {{{q(name)}, std::span(fields + {offset}, {size})}}," for name, offset, size in spans]
    return "\n".join([*lines, "};", "}", ""])


if __name__ == "__main__":
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    source = generate()
    if args.check:
        if not TARGET.exists() or TARGET.read_text(encoding="utf-8") != source:
            raise SystemExit("Source inspection schema is stale; run tools/generate-source-inspection-schema.py")
        print("PASS: source inspection field names match both frozen descriptors")
    else:
        TARGET.parent.mkdir(parents=True, exist_ok=True)
        TARGET.write_text(source, encoding="utf-8", newline="\n")
        print("Generated source inspection schema")
