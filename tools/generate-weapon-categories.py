"""Generate PUBG category bindings from the existing local public-reference archive; no network."""
import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "data/games/pubg/weapons/2026-10-15/pubg-gs.json"
TARGET = ROOT / "src/games/pubg/data/weapon_categories.inc"
CATEGORIES = {"SR": "Sniper", "DMR": "Marksman", "AR": "AssaultRifle", "SMG": "SubmachineGun",
              "LMG": "LightMachineGun", "Shotgun": "Shotgun", "Handgun": "Handgun",
              "Launcher": "Other", "Melee": "Other", "Special": "Other", "Crossbow": "Other"}


def generated():
    weapons = json.loads(SOURCE.read_text(encoding="utf-8"))["weapons"]
    ids = [w["item_id"] for w in weapons]
    if len(set(ids)) != len(ids):
        raise ValueError("Duplicate weapon identity")
    lines = ["// Generated by tools/generate-weapon-categories.py from the archived category field.",
             "// SR is the source family, including Lynx AMR and Win94; it does not assert a bolt-action mechanism."]
    for weapon in sorted(weapons, key=lambda w: w["item_id"]):
        lines.append(f'{{"{weapon["item_id"]}", WeaponCategory::{CATEGORIES[weapon["category"]]}}},')
    return "\n".join(lines) + "\n"


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    expected = generated()
    if args.check:
        if TARGET.read_text(encoding="utf-8") != expected:
            raise SystemExit("PUBG weapon category bindings need regeneration")
    else:
        TARGET.write_text(expected, encoding="utf-8", newline="\n")
    print("PASS: PUBG weapon categories match the local archive")
